export function shippingFeeJpy(subtotalJpy, prefecture) {
  if (!prefecture || !FEES.has(prefecture)) return null;
  if (subtotalJpy >= FREE_SHIPPING_THRESHOLD_JPY) return 0;
  return FEES.get(prefecture);
}
